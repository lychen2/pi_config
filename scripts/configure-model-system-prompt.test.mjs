import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { configureModelSystemPrompt } from "./configure-model-system-prompt.mjs";

test("configuration preserves model presets, scopes GPT refinements, archives the shared prompt, and is repeatable", t => {
  const homeDir = mkdtempSync(join(tmpdir(), "model-prompt-config-"));
  t.after(() => rmSync(homeDir, { recursive: true, force: true }));
  const agent = join(homeDir, "custom-agent");
  const presets = join(agent, "npm", "node_modules", "pi-model-system-prompt", "presets");
  const target = join(homeDir, ".pi", "agent", "model-system-prompt");
  mkdirSync(presets, { recursive: true });
  mkdirSync(target, { recursive: true });
  writeFileSync(join(presets, "gpt-6-astra.md"), "NPM ASTRA PRESET\n");
  writeFileSync(join(presets, "gpt-6-luna.md"), "NPM LUNA PRESET\n");
  writeFileSync(join(presets, "claude-opus-5.md"), "NPM CLAUDE PRESET\n");
  writeFileSync(join(target, "gpt-6-astra.md"), "CUSTOM ASTRA PRESET\n");
  writeFileSync(join(target, "gpt-6-luna.md"), "");
  writeFileSync(join(target, "kimi.md"), "CUSTOM KIMI PRESET\n");
  writeFileSync(join(agent, "APPEND_SYSTEM.md"), "RETIRED GLOBAL RULES\n");
  configureModelSystemPrompt({ homeDir, agentDir: agent, dryRun: true });
  assert.equal(readFileSync(join(target, "gpt-6-astra.md"), "utf8"), "CUSTOM ASTRA PRESET\n");
  assert.ok(existsSync(join(agent, "APPEND_SYSTEM.md")));
  assert.equal(existsSync(join(target, "gemini.md")), false);
  const { backupDir } = configureModelSystemPrompt({ homeDir, agentDir: agent });
  const gpt = readFileSync(join(target, "gpt-6-astra.md"), "utf8");
  assert.match(gpt, /^CUSTOM ASTRA PRESET\n/);
  const guidance = readFileSync(new URL('../config/model-system-prompt/gpt-overrides.md', import.meta.url), 'utf8').trim();
  const injected = gpt.match(/<!-- pi_config:gpt-overrides:start -->\n([\s\S]*?)\n<!-- pi_config:gpt-overrides:end -->/)?.[1];
  assert.equal(injected, guidance);
  assert.equal(readFileSync(join(target, "gpt-6-luna.md"), "utf8"), "");
  assert.equal(readFileSync(join(target, "claude-opus-5.md"), "utf8"), "NPM CLAUDE PRESET\n");
  assert.equal(readFileSync(join(target, "kimi.md"), "utf8"), "CUSTOM KIMI PRESET\n");
  const gemini = readFileSync(join(target, "gemini.md"), "utf8");
  assert.equal(gemini, readFileSync(new URL('../config/model-system-prompt/gemini.md', import.meta.url), 'utf8'));
  assert.doesNotMatch(gemini, /pi_config:gpt-overrides|Local GPT guidance/);
  writeFileSync(join(target, "gemini.md"), "CUSTOM GEMINI PRESET\n");
  assert.equal(readFileSync(join(backupDir, "APPEND_SYSTEM.md"), "utf8"), "RETIRED GLOBAL RULES\n");
  assert.equal(readFileSync(join(backupDir, "preset-gpt-6-astra.md"), "utf8"), "CUSTOM ASTRA PRESET\n");
  assert.equal(existsSync(join(agent, "APPEND_SYSTEM.md")), false);
  assert.deepEqual(configureModelSystemPrompt({ homeDir, agentDir: agent }).updated, []);
  assert.equal(readFileSync(join(target, "gpt-6-astra.md"), "utf8"), gpt);
  assert.equal(readFileSync(join(target, "gemini.md"), "utf8"), "CUSTOM GEMINI PRESET\n");
});
